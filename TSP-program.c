#include<stdio.h>
#include<math.h>
#include<stdlib.h>
#define u01 rand()/(RAND_MAX + 1.0)
#define MAXIMUM 100
#define MINIMUM 20
int cost[1000][1000];
int p[1000],x[1000],y[1000];
float pheromone_update[1000][1000];

float distance(int a1,int b1,int a2,int b2){
	float p = sqrt(( (a1 - b1)* (a1 - b1)) + ( (a2 - b2) * (a2 - b2)));
	return p;
}
int main()
{
	FILE *fp;
	fp=fopen("TSP-2.txt","r");
//	fp=fopen("sample.txt","r");
	int i,j,k;

	int p[100],x[100],y[100];
	int c=0;
	
	i=0;
	fscanf(fp,"%d",&p[i]);
	fscanf(fp,"%d",&x[i]);
	fscanf(fp,"%d",&y[i]);
	i++;
	while(!feof(fp)){
		c++;
		fscanf(fp,"%d",&p[i]);
	        fscanf(fp,"%d",&x[i]);	
		fscanf(fp,"%d",&y[i]);
		i++;
	}
	for (i=0; i<c; i++) { p[i] = p[i] - 1; }
	
	fclose(fp);
	
        float cost[c][c];
        //cost matrix 
	for(i=0;i<c;i++){
		for(j=0;j<c;j++){
			cost[i][j]=distance(x[i],x[j],y[i],y[j]);
			
		}
		
	}
	
	
	int n = c; //no of cities
	int m; //number of ants
	int ant_to_city[1000];//declare ant---> start node
	int itr = 0;
	float iteration_best_cost=100000;
	int iteration_best_sol[n];
	for(i=0;i<n;i++){
			iteration_best_sol[i] = -1;
	}
	//initialising pheromone value
	for(i=0;i<n;i++){
		for(j=0;j<n;j++){
			pheromone_update[i][j] = MAXIMUM;
		}
	}
	while(itr< 1000){
	//	printf("\nitr%d\n",itr);
		m=u01 * 200; //no. of ants generated
		
		//assign a city to each ant
		for(i=0; i<m; i++){
		
			ant_to_city[i]=(int)(u01 * n); 
			
		}
		
		for(i=0; i<m; i++){//travel each ant
		//	printf("\n%d->",i);
			int kth_ant_travel[n];
			int j;
			int visited_city[n];
			for(j=0;j<n;j++){
				visited_city[j]= 0;
			}
			kth_ant_travel[0]= ant_to_city[i];
			visited_city[kth_ant_travel[0]] = 1;

			for(j=1;j<n;j++){// choosing next vertex
			//	printf("itr:%d of ant:%d in city:%d\n",itr,i,j);	
	//			printf("A%d ",j);			
				float roulet_wheel[n];
				int city1 = kth_ant_travel[j-1];
				float sum = 0; 
				int k;
				for( k=0; k<n; k++ ){
					if(visited_city[k]==1){
						roulet_wheel[k]=0;
						continue;
					}
					else{
						sum += pheromone_update[city1][k];
						roulet_wheel[k]=sum;
					}
					
				}		
				
				
				// new_city generated by " roulet wheel selection method "
				if(sum== MAXIMUM*(n-1)){
	//				printf("B%d:%d ",i,j);
					int rand_city=u01*n;
					while(visited_city[rand_city]==1){
						rand_city = u01*n;
					}
					visited_city[rand_city] = 1;
					kth_ant_travel[j] = rand_city;
					
				}
				else{
				//	printf("C ");
					int rand_num= u01 * sum;
					int t,next_city;
					for(t=0;t<n;t++){
						if(rand_num < roulet_wheel[t]){
							next_city = t;
						}
					}

				//	int a=0;
					while(visited_city[next_city] == 1){
						int rand_num1= u01 * sum;
							for(t=0;t<n;t++){
								if(rand_num1 < roulet_wheel[t]){
									next_city = t;
								}
							}
					}
					visited_city[next_city] = 1;
					kth_ant_travel[j] = next_city;
				}
			}//end of choosing next vertex
			
			//checking the cost value
		//	printf("Ee ");
			float total_value=0;
			for( j=0;j<n;j++){
				if(j==n-1){
					total_value += cost[kth_ant_travel[j]][kth_ant_travel[0]];
					
				}
				else{
					total_value += cost[kth_ant_travel[j]][kth_ant_travel[j+1]];
					
				}
			}
			if(total_value < iteration_best_cost){
	//			printf("AIC:%.2f ",total_value);
				iteration_best_cost = total_value;
				for(j=0;j<n;j++){
					iteration_best_sol[j] = kth_ant_travel[j];
				}
			}
			
		}//ant generation end
			
		//APPLY LOCAL SEARCH ON best solution in the iteration
	//	printf("F ");
		int local_search_array[n];		
		int total = 10000;
		float local_cost = iteration_best_cost;
		int temp_array[n];
		int counter =0;
		float value = iteration_best_cost;
		int cx =0;
		while(total > local_cost){
			for(j=0;j<n;j++){ 
				local_search_array[j]=iteration_best_sol[j];
			}
			int p,q;
			p= u01*n;
			q=u01*n;
			while(q == p ){
				q=u01*n;
			}
			int tmp = local_search_array[p];
			local_search_array[p] = local_search_array[q];
			local_search_array[q] = tmp;
			
			total=0;
			for( j=0;j<n;j++){
				if(j==n-1){
					total += cost[local_search_array[j]][local_search_array[0]];
				}
				else{
					total += cost[local_search_array[j]][local_search_array[j+1]];
				}
			}
	//		printf("X ");
			if(total < local_cost){
				local_cost = total;
				value = local_cost;
				cx++;
				for(j=0;j<n;j++){
					temp_array[j] = local_search_array[j];
			//		printf("%d-->>>",iteration_best_sol[j]);
				}
		//		break;
			}		
			
			if(value == local_cost){
				counter++;
			}
			else{
				counter = 0;
			}
			if(counter ==200000){
				printf("cnt:%d",counter);
				break;	
			}
				
	//		printf("\n<%d> cost:%.2f I:%.2f\n",itr,local_cost,iteration_best_cost);
		}
	//	printf("cx:%d ",cx);
		if(local_cost < iteration_best_cost){
	//		printf(" LSC:%.2f ",local_cost);
			iteration_best_cost = local_cost;
			for(k=0;k<n;k++){
				iteration_best_sol[k]=temp_array[k];
			}
		}
		
	//	printf("Ff ");
		//EVAPOURATION
		if(itr != 0){
			for(j=0;j<n;j++){
				for(k=0;k<n;k++){
					
					pheromone_update[j][k] = 0.8 * pheromone_update[j][k];
					
				}
			}
		}
	//	printf("G ");
		// PHEROMONE UPDATE
		for(j=0;j<n-1;j++){
			pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ] = pheromone_update[iteration_best_sol[j]][iteration_best_sol[j+1]] + 1/( iteration_best_cost);
			
			if(pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ] < MINIMUM){
				pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ] = MINIMUM;
			}
			
			if(pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ] > MAXIMUM ){
				pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ] = MAXIMUM;
			}
			
			pheromone_update[ iteration_best_sol[j+1] ][ iteration_best_sol[j] ]=pheromone_update[ iteration_best_sol[j] ][ iteration_best_sol[j+1] ];
		}
				
		//iteration END
//		printf("enditr%d ",itr);
		itr++;
		
		
	}
	printf("THE FINAL RESULT:\n");
	printf("cost: %.2f\n",iteration_best_cost);
	printf("path\n");
	for(i=0;i<n;i++){
		printf("%d ",iteration_best_sol[i]);
	}
	printf("\n");
}
